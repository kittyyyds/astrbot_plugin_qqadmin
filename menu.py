PAGE_ALIASES = {"": "home", "首页": "home", "主页": "home", "home": "home"}
for index, (key, section) in enumerate(MENU_SECTIONS.items(), 1):
    for alias in (key, str(index), section["keyword"], section["title"]):
        PAGE_ALIASES[alias] = key


def get_menu_page(category: str = "") -> str | None:
    return PAGE_ALIASES.get(category.strip().casefold())


def menu_image_path(page: str) -> Path:
    if page not in {"home", *MENU_SECTIONS}:
        raise ValueError("Unknown menu page")
    return Path(__file__).resolve().parent / "assets" / "menu" / f"{page}.png"


def menu_text(page: str) -> str:
    if page not in {"home", *MENU_SECTIONS}:
        raise ValueError("Unknown menu page")
    lines = ["Kitty 群管"]
    sections = MENU_SECTIONS.values() if page == "home" else [MENU_SECTIONS[page]]
    for section in sections:
        lines.extend(["", section["title"]])
        if page == "home":
            lines.extend(f"{syntax} - {description}" for syntax, description in section["featured"])
            lines.append(f"完整用法：菜单 {section['keyword']}")
        else:
            lines.extend(f"{syntax} - {description}" for _, syntax, description in section["commands"])
    lines.append("\n管理操作需要相应群权限，权限以本群配置为准。")
    lines.append("群内口令可直接发送，也兼容原唤醒前缀。")
    return "\n".join(lines)
